import Link from "next/link";
import type { Metadata } from "next";
import {
  armCI,
  deriveHeadline,
  fmtDelta,
  fmtP,
  loadBenchmarkSummary,
  pWithOperator,
} from "@/lib/results";

export const metadata: Metadata = {
  title: "Benchmark",
  description:
    "Per-arm accuracy, Wilson 95% CIs and paired McNemar tests for the plain -> plain_rr -> graph -> graph_concepts PubMedQA ablation.",
};

const REPO = "https://github.com/vardhjain/graphrag-pubmedqa-ablation";

function fmtPct(n: number) {
  return `${n.toFixed(1)}%`;
}

function fmtCI(ci: [number, number] | undefined) {
  return ci ? `${ci[0].toFixed(1)}–${ci[1].toFixed(1)}%` : "n/a";
}

function fmtRecall(r: number | null | undefined) {
  return r != null ? `${(r * 100).toFixed(1)}%` : "n/a";
}

export default function BenchmarkPage() {
  const summary = loadBenchmarkSummary();
  const headline = deriveHeadline(summary);
  // Hide a column only when *every* row lacks the field (older summary.json).
  // The CI is always shown: when absent it is derived from accuracy+samples.
  const showRecall = summary.arms.some((a) => a.recall_at_k != null);
  const showHolm = summary.contrasts.some((c) => c.p_holm != null || c.p_holm_display != null);
  const winner = summary.arms.length
    ? summary.arms.reduce((a, b) => (b.accuracy > a.accuracy ? b : a))
    : null;

  return (
    <div className="min-h-screen bg-zinc-50">
      <header className="border-b border-gray-200 bg-white px-6 py-4">
        <div className="max-w-4xl mx-auto">
          <div className="flex items-center justify-between">
            <h1 className="text-lg font-semibold text-zinc-900">Benchmark</h1>
            <div className="flex items-center gap-4">
              <Link href="/case-study" className="text-sm text-blue-600 hover:underline">
                Case study
              </Link>
              <Link href="/" className="text-sm text-blue-600 hover:underline">
                &larr; Back to chat
              </Link>
            </div>
          </div>
          <p className="text-sm text-zinc-600 mt-1">
            {headline.armCount}-arm ablation on {summary.dataset}, n={summary.n}, seed=
            {summary.seed}, model{" "}
            <code className="text-xs bg-gray-100 px-1 rounded">{summary.model}</code>. Numbers
            read at build time from{" "}
            <a
              href={`${REPO}/blob/main/results/summary.json`}
              target="_blank"
              rel="noreferrer"
              className="text-blue-600 hover:underline"
            >
              results/summary.json
            </a>{" "}
            (generated by <code className="text-xs bg-gray-100 px-1 rounded">scripts/compare.py</code>).
          </p>
        </div>
      </header>

      <main className="max-w-4xl mx-auto px-6 py-8 space-y-10">
        <section>
          <h2 className="text-sm font-semibold text-zinc-700 uppercase tracking-wide mb-3">
            Per-arm results
          </h2>
          <div className="overflow-x-auto rounded-lg border border-gray-200 bg-white">
            <table className="w-full text-sm">
              <thead>
                <tr className="border-b border-gray-200 text-left text-zinc-600">
                  <th className="px-4 py-2 font-medium">Arm</th>
                  <th className="px-4 py-2 font-medium">Accuracy</th>
                  <th className="px-4 py-2 font-medium">95% CI</th>
                  <th className="px-4 py-2 font-medium">Macro F1</th>
                  {showRecall && <th className="px-4 py-2 font-medium">Recall@k</th>}
                  <th className="px-4 py-2 font-medium">Avg latency</th>
                  <th className="px-4 py-2 font-medium">Adds</th>
                </tr>
              </thead>
              <tbody>
                {summary.arms.map((arm) => (
                  <tr
                    key={arm.arm}
                    className={`border-b border-gray-100 last:border-0 ${
                      arm.arm === winner?.arm ? "bg-green-50" : ""
                    }`}
                  >
                    <td className="px-4 py-2 font-mono text-xs">
                      {arm.arm}
                      {arm.arm === winner?.arm && (
                        <span className="ml-2 inline-block rounded-full bg-green-600 text-white text-[10px] px-2 py-0.5 align-middle">
                          winner
                        </span>
                      )}
                      {!!arm.n_failed && (
                        <span className="ml-2 text-[10px] text-amber-600" title="LLM calls that exhausted retries, recorded as a placeholder 'maybe'">
                          {arm.n_failed} failed
                        </span>
                      )}
                    </td>
                    <td className="px-4 py-2 font-medium">{fmtPct(arm.accuracy)}</td>
                    <td className="px-4 py-2 text-zinc-600 text-xs">{fmtCI(armCI(arm))}</td>
                    <td className="px-4 py-2">{fmtPct(arm.macro_f1)}</td>
                    {showRecall && <td className="px-4 py-2">{fmtRecall(arm.recall_at_k)}</td>}
                    <td className="px-4 py-2">{arm.avg_latency.toFixed(1)}s</td>
                    <td className="px-4 py-2 text-zinc-600">{arm.adds}</td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        </section>

        <section>
          <h2 className="text-sm font-semibold text-zinc-700 uppercase tracking-wide mb-3">
            Significance (paired McNemar)
          </h2>
          <p className="text-xs text-zinc-600 mb-2">
            {showHolm
              ? "“Significant?” uses Holm-Bonferroni-adjusted p-values across all contrasts."
              : "“Significant?” uses the raw (unadjusted) McNemar p-value at α=0.05; this summary.json predates Holm adjustment."}
          </p>
          <div className="overflow-x-auto rounded-lg border border-gray-200 bg-white">
            <table className="w-full text-sm">
              <thead>
                <tr className="border-b border-gray-200 text-left text-zinc-600">
                  <th className="px-4 py-2 font-medium">Contrast</th>
                  <th className="px-4 py-2 font-medium">&Delta;acc</th>
                  <th className="px-4 py-2 font-medium">Gains / losses</th>
                  <th className="px-4 py-2 font-medium">p-value</th>
                  {showHolm && <th className="px-4 py-2 font-medium">p (Holm)</th>}
                  <th className="px-4 py-2 font-medium">Significant?</th>
                </tr>
              </thead>
              <tbody>
                {summary.contrasts.map((c) => (
                  <tr key={`${c.from}-${c.to}`} className="border-b border-gray-100 last:border-0">
                    <td className="px-4 py-2">
                      <span className="font-mono text-xs">{c.from}</span> &rarr;{" "}
                      <span className="font-mono text-xs">{c.to}</span>
                      <span className="text-zinc-600"> ({c.effect})</span>
                    </td>
                    <td className={`px-4 py-2 font-medium ${c.delta_acc > 0 ? "text-green-700" : "text-red-700"}`}>
                      {fmtDelta(c.delta_acc)}
                    </td>
                    <td className="px-4 py-2 text-zinc-600">
                      {c.gains} / {c.losses}
                    </td>
                    <td className="px-4 py-2 font-mono text-xs">{c.p_display ?? fmtP(c.p_value)}</td>
                    {showHolm && (
                      <td className="px-4 py-2 font-mono text-xs text-zinc-600">
                        {c.p_holm_display ?? (c.p_holm != null ? fmtP(c.p_holm) : "n/a")}
                      </td>
                    )}
                    <td className="px-4 py-2">
                      {c.significant ? (
                        <span className="text-green-700 font-medium">yes</span>
                      ) : (
                        <span className="text-zinc-600">no</span>
                      )}
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        </section>

        <section className="text-sm text-zinc-600 leading-relaxed">
          <h2 className="text-sm font-semibold text-zinc-700 uppercase tracking-wide mb-3">
            Honest summary
          </h2>
          <p>
            The graph arm&apos;s win is one specific mechanism, not &quot;a knowledge graph&quot; in
            the abstract: <strong>parent-document expansion</strong>
            {headline.parentExpansion && (
              <>
                {" "}
                changes accuracy by {fmtDelta(headline.parentExpansion.delta_acc)} over the
                reranked baseline (paired McNemar {pWithOperator(headline.parentExpansion)})
              </>
            )}
            .
            {headline.conceptHop && (
              <>
                {" "}
                The further MeSH concept-hop arm{" "}
                {headline.conceptHop.significant ? "does" : "does not"} clear significance
                against the plain graph arm ({pWithOperator(headline.conceptHop)})
                {headline.conceptLatencyRatio != null && (
                  <> and costs ~{headline.conceptLatencyRatio.toFixed(1)}x the latency</>
                )}
                {headline.conceptHop.significant
                  ? "."
                  : ", so it is not the recommended arm to ship."}
              </>
            )}{" "}
            See{" "}
            <a
              href={`${REPO}/blob/main/RESULTS.md`}
              target="_blank"
              rel="noreferrer"
              className="text-blue-600 hover:underline"
            >
              RESULTS.md
            </a>{" "}
            for the full write-up.
          </p>
        </section>
      </main>
    </div>
  );
}
